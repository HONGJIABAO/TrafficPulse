with open("frontend/src/data/stations.json", "r", encoding="utf-8") as f:
    data = json.load(f)

stations = data["stations"]
matched = 0
unmatched = []

for s in stations:
    name = s["name"]
    # Clean up name if needed
    clean_name = name.strip()
    if clean_name in STATION_COORDS:
        lat, lng = STATION_COORDS[clean_name]
        s["lat"] = lat
        s["lng"] = lng
        matched += 1
    else:
        # Fallback check
        found = False
        for k, v in STATION_COORDS.items():
            if k.lower() == clean_name.lower() or k.lower() in clean_name.lower():
                s["lat"] = v[0]
                s["lng"] = v[1]
                matched += 1
                found = True
                break
        if not found:
            unmatched.append(clean_name)
            # Default to KL center with slight jitter so not missing
            s["lat"] = 3.1390
            s["lng"] = 101.6869

print(f"Matched {matched}/{len(stations)} stations.")
if unmatched:
    print(f"Unmatched ({len(unmatched)}):", unmatched)

with open("frontend/src/data/stations.json", "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

